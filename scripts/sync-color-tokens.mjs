import { readFileSync, writeFileSync } from 'node:fs';

const manifest = JSON.parse(readFileSync(new URL('../docs/color-system.json', import.meta.url), 'utf8'));
const primitive = new Map(manifest.primitives.map(token => [token.name, token]));
const semantic = new Map(manifest.semantics.map(token => [token.name, token]));
if (primitive.size !== manifest.primitives.length || semantic.size !== manifest.semantics.length)
  throw new Error('Duplicate color token names');
const cssNames = new Set([...primitive.values(), ...semantic.values()].map(token => token.cssVariable));
if (cssNames.size !== primitive.size + semantic.size) throw new Error('Duplicate color CSS variables');
for (const token of primitive.values()) {
  if (!/^#[\da-f]{6}(?:[\da-f]{2})?$/i.test(token.hex)) throw new Error(`Invalid color: ${token.name}`);
}
for (const token of semantic.values()) {
  if (!primitive.has(token.alias)) throw new Error(`Unresolved color alias: ${token.name} -> ${token.alias}`);
}
const lines = [
  '  /* Vibecoding color definitions: generated by scripts/sync-color-tokens.mjs. */',
  ...manifest.primitives.map(token => `  ${token.cssVariable}: ${token.hex.toLowerCase()};`),
  ...manifest.semantics.map(token => `  ${token.cssVariable}: var(${primitive.get(token.alias).cssVariable});`),
  '  /* End Vibecoding color definitions. */',
];
const target = new URL('../src/ui/tokens.css', import.meta.url);
let css = readFileSync(target, 'utf8');
const generated = /  \/\* Vibecoding color definitions:[\s\S]*?  \/\* End Vibecoding color definitions\. \*\//;
if (generated.test(css)) css = css.replace(generated, lines.join('\n'));
else {
  if (!css.includes(':root {')) throw new Error('Missing :root; token file was not changed');
  css = css.replace(':root {', `:root {\n${lines.join('\n')}`);
}
writeFileSync(target, css);
console.log(`Synced ${primitive.size} Primitive and ${semantic.size} Semantic definitions; other tokens preserved.`);
