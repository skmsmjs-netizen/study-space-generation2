import { readFile, writeFile } from 'node:fs/promises';
import { materialColor } from './sync-observatory-ui.mjs';

const root = new URL('../', import.meta.url);
const source = 'docs/observatory-experience-baseline.json';
const baseline = JSON.parse(await readFile(new URL(source, root), 'utf8'));
const colorRoles = [
  'canvas',
  'surface',
  'subtle',
  'text',
  'muted',
  'borderDecorative',
  'borderInteractive',
  'focus',
  'selected',
  'selectedText',
  'primary',
  'primaryHover',
  'primaryPressed',
  'onPrimary',
];
const radiusRoles = ['button', 'input', 'tab', 'panel', 'dialog', 'toast'];
const name = (role) =>
  `--math-observatory-${role.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)}`;
const aliases = {
  '--color-background-canvas': 'canvas',
  '--color-background-surface': 'surface',
  '--color-background-raised': 'surface',
  '--color-background-subtle': 'subtle',
  '--color-background-selected': 'selected',
  '--color-text-primary': 'text',
  '--color-text-secondary': 'muted',
  '--color-text-tertiary': 'muted',
  '--color-text-placeholder': 'muted',
  '--color-text-brand': 'primary',
  '--color-text-link': 'primary',
  '--color-text-link-hover': 'primaryHover',
  '--color-border-subtle': 'borderDecorative',
  '--color-border-default': 'borderInteractive',
  '--color-border-strong': 'borderInteractive',
  '--color-border-brand': 'focus',
  '--color-focus-ring': 'focus',
  '--color-icon-primary': 'text',
  '--color-icon-secondary': 'muted',
  '--color-icon-brand': 'focus',
  '--color-button-primary-background-default': 'primary',
  '--color-button-primary-background-hover': 'primaryHover',
  '--color-button-primary-background-pressed': 'primaryPressed',
  '--color-button-primary-text-default': 'onPrimary',
  '--color-button-secondary-background-default': 'surface',
  '--color-button-secondary-background-hover': 'subtle',
  '--color-button-secondary-background-pressed': 'selected',
  '--color-button-secondary-text-default': 'text',
  '--color-button-neutral-background-default': 'surface',
  '--color-button-neutral-background-hover': 'subtle',
  '--color-button-neutral-background-pressed': 'selected',
  '--color-button-neutral-text-default': 'text',
  '--color-button-neutral-border-default': 'borderInteractive',
  '--color-primary': 'primary',
  '--color-on-primary': 'onPrimary',
  '--color-primary-hover': 'primaryHover',
  '--color-primary-pressed': 'primaryPressed',
  '--color-secondary': 'subtle',
  '--color-background': 'canvas',
  '--color-surface': 'surface',
  '--color-surface-inset': 'subtle',
  '--color-text': 'text',
  '--color-muted': 'muted',
  '--color-border': 'borderDecorative',
  '--color-focus': 'focus',
  '--color-selected': 'selected',
  '--color-placeholder': 'muted',
  '--color-secondary-button-background': 'surface',
  '--color-secondary-button-hover': 'subtle',
  '--color-secondary-button-pressed': 'selected',
};
const colorDeclaration = (role, material, sourceRole = role, indent = '  ') => {
  const value = materialColor(material, sourceRole);
  return `${indent}/* design-token-exception: ${name(role)} -- Generated from ${source} materials.${material}.${sourceRole}; math workspace only. */\n${indent}${name(role)}: ${value};`;
};
const colorDeclarations = (theme, indent = '  ') =>
  [
    ...colorRoles.map((role) =>
      colorDeclaration(role, theme === 'light' ? 'paper' : 'interior', role, indent),
    ),
    colorDeclaration('header-background', 'interior', 'canvas', indent),
    colorDeclaration('header-text', 'interior', 'text', indent),
    colorDeclaration('accent', 'interior', 'primary', indent),
  ].join('\n');
const radii = radiusRoles
  .map((role) => {
    const value = baseline.pixelTreatment?.componentRadiusPx?.[role];
    if (!Number.isFinite(value) || value < 0)
      throw new Error(`Invalid ${source}: pixelTreatment.componentRadiusPx.${role}`);
    const variable = name(`radius-${role}`);
    return `  /* design-token-exception: ${variable} -- Generated from ${source} pixelTreatment.componentRadiusPx.${role}; math workspace only. */\n  ${variable}: ${value === 0 ? '0' : `${value}px`};`;
  })
  .join('\n');
const css = `/* Generated by scripts/sync-math-observatory.mjs from ${source}.
   Scoped to the math workspace and its fullscreen portal. Keep graph meaning colors,
   fonts, touch targets, spacing, disabled/error states and saved theme choice intact. */
.math-explorer {
${colorDeclarations('light')}
${radii}
${Object.entries(aliases)
  .map(([variable, role]) => `  ${variable}: var(${name(role)});`)
  .join('\n')}
  --radius-sm: var(--math-observatory-radius-button);
  --radius-md: var(--math-observatory-radius-tab);
  --radius-lg: var(--math-observatory-radius-panel);
  --radius-overlay: var(--math-observatory-radius-dialog);
}

:root[data-theme='dark'] .math-explorer {
${colorDeclarations('dark')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']):not([data-theme='dark']) .math-explorer {
${colorDeclarations('dark', '    ')}
  }
}
`;
await writeFile(new URL('src/ui/math-observatory-tokens.css', root), css);
console.log(
  `Math observatory tokens: baseline ${baseline.version}, 2 themes, ${radiusRoles.length} radius roles`,
);
