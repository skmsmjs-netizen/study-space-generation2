export function linearUnit(id: string) {
  const concept = catalog.concepts.find((c) => c.id === id);
  if (!concept) throw Error('원문 개념 ID를 확인해야 한다.');
  const coverage = correspondence.concepts.find((c) => c.id === id)!;
  const kind = concept.kind as LinearKind;
  const spec = LINEAR_SPECS[kind];
  const note = LINEAR_READING[id];
  return {
    ...concept,
    classification: coverage.classification,
    reason: coverage.reason,
    sourceId: catalog.source.id,
    sourceHash: catalog.source.sha256,
    sourceLocations: concept.sections.map((s) =>
      catalog.sections.find((x) => x.source_section === s)!,
    ),
    sourceLocationLevel: coverage.sourceLocationLevel,
    originalQuestion: null,
    questionOrigin: '프로젝트 설명용 질문·초기 수치; 원문 문제나 실제 관측 자료가 아니다.',
    question: note?.question ?? questions[id] ?? spec.question,
    currentObservationQuestion: note ? note.question : spec.question,
    relation: concept.role,
    currentRelation: spec.representations,
    conditions: spec.conditions,
    changing: [
      ...(spec.matrix
        ? [
            {
              variable: 'A 또는 [A | b]',
              input: '행렬 성분',
              domain: '실수 유한값, 최대 6행·7열; 틀별 추가 차원 조건',
              initial: spec.matrix,
            },
          ]
        : []),
      ...(spec.t ? [{ variable: 't', ...spec.t, input: '연속 조절과 정확한 수치식' }] : []),
      ...(spec.n ? [{ variable: 'n', ...spec.n, input: '정수 조절과 정확한 정수식' }] : []),
    ],
    fixed: spec.conditions,
    units:
      spec.axis ??
      (spec.isSpatial
        ? ['예제 벡터 좌표 · 단위 없음']
        : ['설명용 수치 · 실제 물리 단위는 추정하지 않음']),
    initialReason: spec.initialReason,
    limitations: [...spec.limitations, ...coverage.limits],
    remaining:
      coverage.classification === '부분 대응'
        ? [
            familyRemaining[kind] ?? '개별 원식·관계·조건을 원문과 추가로 대조한다.',
            ...coverage.limits,
          ]
        : coverage.classification === '추가 구현 필요'
          ? ['실수 고유값 조건을 보존한 직교 삼각화와 일반 실수 행렬의 헤센베르크 변환 단계.']
          : [],
    readingParagraphs: note?.paragraphs ?? [],
    readingTex: note?.tex ?? [],
  };
}
